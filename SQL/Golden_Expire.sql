MERGE `suresh-dataengineering.Golden_layer.Repurchased_curated_data` T
USING 
(SELECT *FROM suresh-dataengineering.Silver_layer.Repurchase_stage_data )AS S
ON  T.CUSTOMER_ID = S.CID
AND T.ORDER_ID = S.OID
AND T.WEB_PROD_ID = CAST(S.WEB_PROD_ID AS STRING)
AND T.IS_ACTIVE = TRUE
WHEN MATCHED AND(
  T.USER_PER_COUNT  IS DISTINCT FROM S.UPC
  OR T.PURCHASED_DATE  IS DISTINCT FROM S.DT
  OR T.RECEIVED_DATE  IS DISTINCT FROM S.R_DT
  OR T.ITEM_PRICE  IS DISTINCT FROM S.PRC
  OR T.QUANTITY  IS DISTINCT FROM S.QTY
  OR T.CUST_AMT  IS DISTINCT FROM S.AMT
  OR T.RECEIVED_QUANTITY  IS DISTINCT FROM S.R_QTY
  OR T.RECEIVED_AMOUNT  IS DISTINCT FROM S.R_AMT
  OR T.GMM_DESC  IS DISTINCT FROM S.GMM_DESC
  OR T.PARENT_MDSE_DIVN_DESC IS DISTINCT FROM S.PARENT_MDSE_DIVN_DESC 
)
THEN UPDATE SET 
EFFECTIVE_END_DATE = CURRENT_TIMESTAMP,
IS_ACTIVE = FALSE;
